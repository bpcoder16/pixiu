package pgsqlx

import (
	"context"
	"fmt"
	"net"
	"os"
	"strconv"
	"testing"
	"time"

	"gorm.io/gorm"
)

func postgres18Endpoint(t *testing.T) Endpoint {
	t.Helper()
	address := os.Getenv("PIXIU_PGSQL_TEST_ADDR")
	if address == "" {
		t.Skip("未设置 PIXIU_PGSQL_TEST_ADDR；时间往返测试需 PostgreSQL 18 测试实例")
	}
	host, portText, err := net.SplitHostPort(address)
	if err != nil {
		t.Fatal(err)
	}
	port, err := strconv.Atoi(portText)
	if err != nil {
		t.Fatal(err)
	}
	return Endpoint{
		Host:     host,
		Port:     port,
		Database: os.Getenv("PIXIU_PGSQL_TEST_DATABASE"),
		Username: os.Getenv("PIXIU_PGSQL_TEST_USERNAME"),
		Password: os.Getenv("PIXIU_PGSQL_TEST_PASSWORD"),
		SSLMode:  "disable",
		Location: "Asia/Shanghai",
	}
}

type timestampRoundTripRow struct {
	ID      int64
	Wall    time.Time `gorm:"type:timestamp without time zone"`
	Instant time.Time
}

func TestPostgreSQL18TimestampRoundTrip(t *testing.T) {
	endpoint := postgres18Endpoint(t)
	location, err := time.LoadLocation(endpoint.Location)
	if err != nil {
		t.Fatal(err)
	}
	values := []time.Time{
		time.Date(2026, 11, 9, 0, 15, 11, 123456000, location),
		time.Date(2026, 11, 9, 23, 45, 12, 654321000, time.FixedZone("UTC-5", -5*60*60)),
	}
	for _, disableCache := range []bool{false, true} {
		for _, sessionZone := range []string{"UTC", "Asia/Shanghai"} {
			t.Run(fmt.Sprintf("disableCache=%t/session=%s", disableCache, sessionZone), func(t *testing.T) {
				client, err := New(Config{
					Name:                  "timestamp-test",
					Master:                endpoint,
					SessionTimeZone:       sessionZone,
					DisableStatementCache: disableCache,
				})
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() {
					if err := client.Close(); err != nil {
						t.Error(err)
					}
				})
				ctx, cancel := context.WithTimeout(t.Context(), 15*time.Second)
				defer cancel()
				// 固定物理连接，只使用临时表；关闭客户端时由 PostgreSQL 自动清理。
				err = client.MasterDB(ctx).Connection(func(db *gorm.DB) error {
					// 每次操作派生独立 Statement，避免查询条件和事务状态污染后续操作。
					db = db.Session(&gorm.Session{NewDB: true})
					var version int
					if err := db.Raw("SHOW server_version_num").Scan(&version).Error; err != nil {
						return err
					}
					if version < 180000 || version >= 190000 {
						return fmt.Errorf("测试要求 PostgreSQL 18，实际 server_version_num=%d", version)
					}
					if err := db.Exec(`CREATE TEMP TABLE pixiu_timestamp_roundtrip (
						id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
						wall timestamp without time zone NOT NULL,
						instant timestamp with time zone NOT NULL
					)`).Error; err != nil {
						return err
					}
					for _, input := range values {
						row := timestampRoundTripRow{
							Wall:    input,
							Instant: input,
						}
						// Create 的 RETURNING 覆盖驱动 Query 路径，Exec 覆盖驱动 Exec 路径；重复执行覆盖描述缓存命中。
						if err := db.Table("pixiu_timestamp_roundtrip").Create(&row).Error; err != nil {
							return err
						}
						for _, operation := range []string{"Create", "Exec"} {
							if operation == "Exec" {
								input = input.Add(time.Minute)
								if err := db.Exec("UPDATE pixiu_timestamp_roundtrip SET wall = ?, instant = ? WHERE id = ?", input, input, row.ID).Error; err != nil {
									return err
								}
							}
							var got timestampRoundTripRow
							if err := db.Raw("SELECT wall, instant FROM pixiu_timestamp_roundtrip WHERE id = ?", row.ID).Scan(&got).Error; err != nil {
								return err
							}
							wantWall := time.Date(input.Year(), input.Month(), input.Day(), input.Hour(), input.Minute(), input.Second(), input.Nanosecond(), location)
							if !got.Wall.Equal(wantWall) || got.Wall.Location().String() != location.String() {
								t.Errorf("%s 的 timestamp 墙上时间发生偏移: got=%s want=%s", operation, got.Wall.Format(time.RFC3339Nano), wantWall.Format(time.RFC3339Nano))
							}
							if !got.Instant.Equal(input) {
								t.Errorf("%s 的 timestamptz 时刻发生偏移: got=%s want=%s", operation, got.Instant.Format(time.RFC3339Nano), input.Format(time.RFC3339Nano))
							}
						}
					}
					var preparedCount int64
					if err := db.Raw("SELECT count(*) FROM pg_prepared_statements WHERE name <> ''").Scan(&preparedCount).Error; err != nil {
						return err
					}
					if disableCache && preparedCount != 0 || !disableCache && preparedCount == 0 {
						t.Errorf("命名预备语句数量不符合开关配置: disableCache=%t count=%d", disableCache, preparedCount)
					}
					return nil
				})
				if err != nil {
					t.Fatal(err)
				}
			})
		}
	}
}
